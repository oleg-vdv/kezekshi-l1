# Операционный шум: правила, где контекстный benign/FP-вердикт памятки надёжнее
# модели. На них памятка закрывает алерт, даже если модель переоценила тяжесть
# (incident). Контекстные функции (_registry/_rootcheck/_fim/_start_type) всё
# равно эскалируют опасные под-случаи - autorun-ключи, rootkit/скрытый процесс,
# критичные пути, защитные службы, - такие возвращают S и сюда НЕ попадают.
# В список НЕ входят вход/подбор/новые пользователи/службы - там сеть
# безопасности по модели сохраняется.
HARD_NOISE = set((
    "750 751 752 594 597 598 "                                  # FIM реестра (autorun -> S контекстом)
    "60602 61102 61110 61061 63102 60778 60775 61108 60776 "    # ошибки приложений/системы Windows
    "61109 61135 61060 "                                        # сетевые/служебные сбои Windows
    "60642 60608 60716 60702 60703 60718 60719 60720 60668 60671 60672 60747 60798 60805 60807 60808 60809 60817 60644 60630 60635 60610 60612 60611 60646 90501 60137 60106 "  # инфо-события Windows
    "61104 "                                                    # смена типа запуска службы (защитная служба -> S контекстом _start_type)
    "202 203 204 205 501 502 503 504 506 657 11 "               # операционные события самого Wazuh
    "52004 40704 591 531 5555 5501 5502 2901 2902 2903 2904 "   # штатные события Linux
    "554 553 550 "                                              # FIM Linux (критичный путь -> S контекстом)
    "510 "                                                      # rootcheck (rootkit -> S контекстом)
    "23502 23503 23504 23505 23506 "                            # уязвимости: план патчей, не инцидент
    "19004 19005 19007 19008 19009 19010 19011 19012 19013 19014 19015"  # CIS: план укрепления
).split())


def hard_benign(rule_id, ev, level=0):
    """Правило из белого списка операционного шума И контекстный вердикт benign/FP.

    Такой алерт памятка закрывает сама, даже если модель сказала incident:
    детерминированная разметка аналитика на этих правилах надёжнее модели.
    """
    rid = str(rule_id)
    if rid not in HARD_NOISE:
        return False
    return label(rid, ev, level)[0] in (B, F)


def label(rule_id, ev, level=0):
    """Вердикт по памятке: (verdict, mitre, why, checks). Неизвестное правило: по уровню."""
    r = R.get(str(rule_id))
    if r is None:
        v = S if level >= 10 else B
        return v, [], "правила нет в памятке, решение по уровню", []
    v, why = (r["when"](ev) if r["when"] else (r["verdict"], r["why"]))
    return v, r["mitre"], why, r["checks"]


def hint(rule_id):
    """Строка подсказки для модели (без контекстных условий)."""
    r = R.get(str(rule_id))
    if r is None:
        return ""
    m = ", ".join(r["mitre"]) or "нет"
    return f"Памятка по правилу {rule_id}: обычно {r['verdict']}; {r['why']}. MITRE: {m}. Проверить: {'; '.join(r['checks']) or 'ничего'}."
