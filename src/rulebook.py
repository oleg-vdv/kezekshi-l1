"""Памятка L1 по правилам Wazuh: вердикт, MITRE, почему, что проверить.

Источник разметки для обучения и подсказка модели. Вердикт может зависеть
от полей алерта: тогда в записи есть функция `when(ev) -> (verdict, why)`.
"""
import re

B, F, S, I = "benign_true_positive", "false_positive", "suspicious", "incident_candidate"

AUTORUN = re.compile(r"\\CurrentVersion\\(Run|RunOnce|Policies\\Explorer\\Run)|\\Winlogon\\|Image File Execution Options|\\Services\\[^\\]+\\ImagePath", re.I)
USER_DIR = re.compile(r"\\(AppData|Temp|Users\\Public|ProgramData|Downloads)\\|/tmp/|/dev/shm/", re.I)
CRIT_PATH = re.compile(r"^/etc/(passwd|shadow|group|sudoers|ssh/|crontab|cron\.)|^/root/\.ssh|authorized_keys|^/var/www/")
SECURITY_SVC = re.compile(r"WinDefend|Windows Defender|EventLog|wuauserv|Sense|MpsSvc|wscsvc", re.I)
# признаки шифровальщика в FIM: расширение зашифрованного файла или записка о выкупе
RANSOM = re.compile(r"\.(lock(ed)?|crypt(ed)?|encrypted|crypto|wncry|wannacry|ryuk|lockbit|conti|makop|phobos|djvu|cerber|locky)(\b|$)"
                    r"|how[ _]?to[ _]?(decrypt|recover)|decrypt[ _]?(instruction|files)|recover[ _]?(your[ _]?)?files"
                    r"|restore[ _]?files|_readme\.txt|ransom|файлы (зашифрован|закодирован)", re.I)

def _blob(ev):
    return " ".join(ev.values())

def _fim(ev):
    path = ev.get("syscheck.path", "")
    if RANSOM.search(path) or RANSOM.search(_blob(ev)):
        return I, "признак шифровальщика: зашифрованное расширение или записка о выкупе в FIM"
    if CRIT_PATH.search(path):
        return S, f"изменён критичный файл {path}: учётные записи, доступ или автозапуск"
    return B, "изменение системного файла, обычно след обновления пакетов"

def _registry(ev):
    if AUTORUN.search(_blob(ev)):
        return S, "изменение ключа автозапуска: так закрепляются вредоносы"
    return B, "штатное изменение реестра Windows"

def _rootcheck(ev):
    log = ev.get("full_log", "")
    if "/var/lib/docker/overlay2/" in log or "/var/lib/containerd/" in log:
        return F, "rootcheck срабатывает на файлы слоёв Docker, это известный ложный сигнал"
    if re.search(r"hidden (process|port)|rootkit|kernel module", log, re.I):
        return S, "rootcheck нашёл признак скрытого процесса/порта или руткита"
    if re.search(r"trojan", log, re.I):
        # сигнатурная проверка 'Trojaned version of file' почти всегда ложна на
        # обновлённых дистрибутивах (хэш бинарника разошёлся с базой rootcheck)
        return F, "rootcheck 'trojaned version of file' - сигнатурный чек, обычно ложный после обновления пакетов"
    return B, "замечание rootcheck о правах или владельце файла"

def _new_service(ev):
    if USER_DIR.search(_blob(ev)):
        return S, "служба запускает файл из пользовательского или временного каталога"
    return B, "служба установлена из штатного каталога программ"

def _start_type(ev):
    if SECURITY_SVC.search(_blob(ev)):
        return S, "изменён тип запуска защитной службы"
    return B, "изменён тип запуска обычной службы"

def _ssh_src(ev):
    ip = ev.get("data.srcip", "")
    if ip.startswith(("10.", "192.168.", "172.16.", "127.")):
        return S, f"попытки идут из внутренней сети ({ip}): атакующий может быть уже внутри"
    return B, "одиночный фон из интернета, на открытый SSH такое приходит постоянно"

R = {}
def rule(ids, verdict, mitre, why, checks, when=None):
    for i in ids.split():
        R[i] = {"verdict": verdict, "mitre": mitre, "why": why, "checks": checks, "when": when}

